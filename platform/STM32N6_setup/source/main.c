// Get Jedec ID
int getJedecId(PLAT_SPI_FORMAT_T format, uint8_t* mfgId, uint8_t* memoryType, uint8_t* capacity)
{
    uint8_t bufTx[1] = {0};
    uint8_t bufRx[3] = {0};

    bufTx[0] = SPI_FLASH_CMD__READ_JEDEC;

    PLAT_SPI_WriteReadTransaction(NULL, format, 0, bufTx, 1, 0, 0, 0, bufRx, sizeof(bufRx));

    *mfgId = bufRx[0];
    *memoryType = bufRx[1];
    *capacity = bufRx[2];
    return 0;
}

