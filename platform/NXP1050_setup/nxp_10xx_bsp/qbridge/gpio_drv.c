/*---------------------------------------------------------------------------------------------------------*/
/*                                                INCLUDES                                                 */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
#include "common_platform_gpio.h"
#include "fsl_gpio.h"
#include "board.h"

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                                 DEFINES                                                 */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
#define PLAT_GPIO_NUM_OF_PORTS      (5)
#define PLAT_GPIO_MAX_BITS_PER_PORT (32)

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                               LOCAL TYPES                                               */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
typedef enum PLAT_GPIO_PORT_STATE_T
{
    PLAT_GPIO_PORT_STATE_UNINITIALIZED = 0,
    PLAT_GPIO_PORT_STATE_INITIALIZED,
} PLAT_GPIO_PORT_STATE_T;

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                                 LOCALS                                                  */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
static PLAT_GPIO_PORT_STATE_T PLAT_GPIO_portState[PLAT_GPIO_NUM_OF_PORTS];
static GPIO_Type *GPIO[PLAT_GPIO_NUM_OF_PORTS] = {GPIO1, GPIO2, GPIO3, GPIO4, GPIO5};

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                       PLATFORM SPECIFIC FUNCTIONS                                       */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/

int PLAT_GPIO_Init(void* user_data)
{
    memset(PLAT_GPIO_portState, 0x0, sizeof(PLAT_GPIO_portState));

    return 0;
}

int PLAT_GPIO_Finit(void)
{
    return 0;
}

int PLAT_GPIO_ConfigInput(uint32_t gpioPinNum)
{
    uint32_t port = PLAT_GPIO_PORT(gpioPinNum);
    uint32_t bit  = PLAT_GPIO_BIT(gpioPinNum);

    gpio_pin_config_t pinConf = {
            kGPIO_DigitalInput,
            0,
            kGPIO_NoIntmode
    };

    /*-----------------------------------------------------------------------------------------------------*/
    /* Error checking                                                                                      */
    /*-----------------------------------------------------------------------------------------------------*/
    if (port >= PLAT_GPIO_NUM_OF_PORTS) return -1;
    if (bit >= PLAT_GPIO_MAX_BITS_PER_PORT) return -1;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Initialize the port if needed                                                                       */
    /*-----------------------------------------------------------------------------------------------------*/
    if (PLAT_GPIO_PORT_STATE_UNINITIALIZED == PLAT_GPIO_portState[port])
    {
        PLAT_GPIO_portState[port] = PLAT_GPIO_PORT_STATE_INITIALIZED;
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Initialize the pin                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    GPIO_PinInit(GPIO[port], bit, &pinConf);

    return 0;
}

int PLAT_GPIO_ConfigOutput(uint32_t gpioPinNum, bool initVal)
{
    uint32_t port = PLAT_GPIO_PORT(gpioPinNum);
    uint32_t bit  = PLAT_GPIO_BIT(gpioPinNum);

    gpio_pin_config_t pinConf = {
            kGPIO_DigitalOutput,
            (true == initVal) ? 1 : 0,
            kGPIO_NoIntmode
    };

    /*-----------------------------------------------------------------------------------------------------*/
    /* Error checking                                                                                      */
    /*-----------------------------------------------------------------------------------------------------*/
    if (port >= PLAT_GPIO_NUM_OF_PORTS) return -1;
    if (bit >= PLAT_GPIO_MAX_BITS_PER_PORT) return -1;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Initialize the port if needed                                                                       */
    /*-----------------------------------------------------------------------------------------------------*/
    if (PLAT_GPIO_PORT_STATE_UNINITIALIZED == PLAT_GPIO_portState[port])
    {
        PLAT_GPIO_portState[port] = PLAT_GPIO_PORT_STATE_INITIALIZED;
    }

    /*-----------------------------------------------------------------------------------------------------*/
    /* Initialize the pin                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    GPIO_PinInit(GPIO[port], bit, &pinConf);

    return 0;
}

int PLAT_GPIO_Read(uint32_t gpioPinNum, bool* val)
{
    uint32_t port = PLAT_GPIO_PORT(gpioPinNum);
    uint32_t bit  = PLAT_GPIO_BIT(gpioPinNum);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Error checking                                                                                      */
    /*-----------------------------------------------------------------------------------------------------*/
    if (port >= PLAT_GPIO_NUM_OF_PORTS) return -1;
    if (bit >= PLAT_GPIO_MAX_BITS_PER_PORT) return -1;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Read the pin value                                                                                  */
    /*-----------------------------------------------------------------------------------------------------*/
    *val = (GPIO_PinRead(GPIO[port], bit) == 0) ? false : true;

    return 0;
}

int PLAT_GPIO_Write(uint32_t gpioPinNum, bool val)
{
    uint32_t port = PLAT_GPIO_PORT(gpioPinNum);
    uint32_t bit  = PLAT_GPIO_BIT(gpioPinNum);

    /*-----------------------------------------------------------------------------------------------------*/
    /* Error checking                                                                                      */
    /*-----------------------------------------------------------------------------------------------------*/
    if (port >= PLAT_GPIO_NUM_OF_PORTS) return -1;
    if (bit >= PLAT_GPIO_MAX_BITS_PER_PORT) return -1;

    /*-----------------------------------------------------------------------------------------------------*/
    /* Write the pin                                                                                       */
    /*-----------------------------------------------------------------------------------------------------*/
    GPIO_PinWrite(GPIO[port], bit, (true == val) ? 1 : 0);

    return 0;
}
